// Variables
//    1. Declare the variable: let X;
//    2. Assign a value to the declared variable: X = 100;
//    3. Test the variable: console.log(X);
//    4. Output will be 100

// Declaring and assigning on two lines
// Commonly used when not knowing the value yet, might come from user input
let X;
X = 100;

console.log(X)

// Declaring and assigning on one line
// Commonly used when you already know the value from the start
let Z = 200;
console.log(Z);
